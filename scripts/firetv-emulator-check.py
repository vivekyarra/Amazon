#!/usr/bin/env python3
"""Android TV emulator runtime check for the Fire OS command HUD (apps/firetv-command-hud).

Boots (optionally) an Android TV AVD, installs the debug APK, connects it to a local
demo backend, signs in and drives all four views ONLY with remote keyevents
(DPAD_*/ENTER/BACK), records screenshots, a screenrecord and a JSON result log.

This is an Android TV *emulator* running a Fire OS-compatible APK. It is NOT a physical
Fire TV device and NOT Vega OS. Results never certify Fire TV device validation.

Prerequisites: backend running in demo mode on the host (scripts/start-local.sh, port 8080),
`.local/access.json` generated by it, an Android SDK with platform-tools/emulator, and a
built APK (gradle -p apps/firetv-command-hud assembleDebug).

The demo-admin password is read from the ignored .local/access.json and typed into the app
through `adb shell input text`; it is never printed or written to the outputs.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import http.cookiejar
import json
import os
import re
import socket
import struct
import subprocess
import sys
import time
import urllib.request
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = "dev.doneirl.tv.debug"
ACTIVITY = f"{PKG}/dev.doneirl.tv.MainActivity"
VIEWS = ["Ledger", "Incident review", "Evidence packet", "Reality-Lock"]
results: list[dict] = []


def sdk_dir() -> Path:
    for key in ("ANDROID_HOME", "ANDROID_SDK_ROOT"):
        if os.getenv(key):
            return Path(os.environ[key])
    if os.name == "nt":
        return Path(os.environ["LOCALAPPDATA"]) / "Android" / "Sdk"
    return Path.home() / "Android" / "Sdk"


SDK = sdk_dir()
ADB = str(SDK / "platform-tools" / ("adb.exe" if os.name == "nt" else "adb"))
EMULATOR = str(SDK / "emulator" / ("emulator.exe" if os.name == "nt" else "emulator"))


def record(step: str, ok: bool, detail: str = "") -> None:
    results.append({"step": step, "ok": ok, "detail": detail, "t": round(time.time(), 1)})
    print(f"[{'PASS' if ok else 'FAIL'}] {step}{' - ' + detail if detail else ''}", flush=True)


class Device:
    def __init__(self, serial: str, out: Path):
        self.serial, self.out = serial, out

    def adb(self, *args: str, check: bool = True, binary: bool = False, timeout: int = 120):
        p = subprocess.run([ADB, "-s", self.serial, *args], capture_output=True, timeout=timeout)
        if check and p.returncode != 0:
            raise RuntimeError(f"adb {' '.join(args[:3])} failed: {p.stderr.decode(errors='replace')[:300]}")
        return p.stdout if binary else p.stdout.decode(errors="replace")

    def key(self, name: str, wait: float = 0.9) -> None:
        self.adb("shell", "input", "keyevent", f"KEYCODE_{name}")
        time.sleep(wait)

    def shot(self, name: str) -> Path:
        path = self.out / f"{name}.png"
        path.write_bytes(self.adb("exec-out", "screencap", "-p", binary=True))
        return path

    def ui_xml(self) -> str:
        """Fresh uiautomator dump. The stale file is deleted first because a dump taken while
        the WebView is still loading can fail ('could not get idle state'); retry then."""
        for _ in range(5):
            self.adb("shell", "rm", "-f", "/sdcard/doneirl-ui.xml", check=False)
            self.adb("shell", "uiautomator", "dump", "/sdcard/doneirl-ui.xml", check=False)
            xml = self.adb("shell", "cat", "/sdcard/doneirl-ui.xml", check=False)
            if "<hierarchy" in xml:
                return xml
            time.sleep(1)
        return ""

    def native_focus(self) -> str:
        """Text/class of the natively focused view (uiautomator)."""
        m = re.search(r'<node [^>]*?text="([^"]*)"[^>]*?class="([^"]*)"[^>]*?focused="true"', self.ui_xml())
        if not m:
            return ""
        return m.group(1) or m.group(2).rsplit(".", 1)[-1]

    def screen_text(self) -> str:
        return " | ".join(re.findall(r'text="([^"]+)"', self.ui_xml()))

    def top_package(self) -> str:
        out = self.adb("shell", "dumpsys", "activity", "activities", check=False)
        m = re.search(r"(?:mResumedActivity|topResumedActivity)[^\n]*? ([\w.]+)/", out)
        return m.group(1) if m else ""


class DevTools:
    """Minimal stdlib Chrome DevTools client for the debug WebView (read-only inspection)."""

    def __init__(self, dev: Device, port: int = 9333):
        self.dev, self.port = dev, port

    def _ws_url(self) -> str:
        pid = self.dev.adb("shell", "pidof", PKG, check=False).strip()
        self.dev.adb(
            "forward", f"tcp:{self.port}", f"localabstract:webview_devtools_remote_{pid}", check=False
        )
        pages = json.loads(urllib.request.urlopen(f"http://127.0.0.1:{self.port}/json", timeout=5).read())
        page = next(p for p in pages if p.get("type") == "page")
        return page["webSocketDebuggerUrl"]

    def evaluate(self, expression: str):
        url = self._ws_url()
        host, path = re.match(r"ws://([^/]+)(/.*)", url).groups()
        h, _, p = host.partition(":")
        s = socket.create_connection((h, int(p or 80)), timeout=10)
        key = base64.b64encode(os.urandom(16)).decode()
        s.sendall(
            f"GET {path} HTTP/1.1\r\nHost: {host}\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n"
            f"Sec-WebSocket-Key: {key}\r\nSec-WebSocket-Version: 13\r\n\r\n".encode()
        )
        buf = b""
        while b"\r\n\r\n" not in buf:
            buf += s.recv(4096)
        rest = buf.split(b"\r\n\r\n", 1)[1]
        msg = json.dumps(
            {
                "id": 1,
                "method": "Runtime.evaluate",
                "params": {"expression": expression, "returnByValue": True},
            }
        ).encode()
        mask = os.urandom(4)
        n = len(msg)
        header = b"\x81" + (bytes([0x80 | n]) if n < 126 else b"\xfe" + struct.pack(">H", n))
        s.sendall(header + mask + bytes(b ^ mask[i % 4] for i, b in enumerate(msg)))
        data = rest
        while True:
            while len(data) < 2:
                data += s.recv(65536)
            ln = data[1] & 0x7F
            off = 2
            if ln == 126:
                while len(data) < 4:
                    data += s.recv(65536)
                ln, off = struct.unpack(">H", data[2:4])[0], 4
            elif ln == 127:
                while len(data) < 10:
                    data += s.recv(65536)
                ln, off = struct.unpack(">Q", data[2:10])[0], 10
            while len(data) < off + ln:
                data += s.recv(65536)
            payload, data = data[off : off + ln], data[off + ln :]
            reply = json.loads(payload)
            if reply.get("id") == 1:
                s.close()
                return reply.get("result", {}).get("result", {}).get("value")

    def active(self) -> str:
        return (
            self.evaluate(
                "(() => { const a = document.activeElement; if (!a || a === document.body) return 'BODY';"
                " const r = a.getBoundingClientRect(); const cs = getComputedStyle(a);"
                " return a.tagName + ':' + (a.innerText || a.value || a.getAttribute('aria-label') || '').trim().slice(0, 40)"
                " + ' | outline=' + cs.outlineStyle + ' ' + cs.outlineWidth + ' | inView=' +"
                " (r.top >= 0 && r.bottom <= innerHeight); })()"
            )
            or ""
        )


class Admin:
    """Backend admin client (host side) for the isolated synthetic demo household."""

    def __init__(self, base: str):
        self.base = base
        self.op = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def call(self, path: str, body=None):
        req = urllib.request.Request(self.base + "/api" + path, method="GET" if body is None else "POST")
        if body is not None:
            req.data = json.dumps(body).encode()
            req.add_header("Content-Type", "application/json")
            req.add_header("Idempotency-Key", str(uuid.uuid4()))
        return json.loads(self.op.open(req, timeout=30).read())

    def login(self, password: str):
        self.call("/auth/login", {"username": "demo-admin", "password": password})

    def studio(self) -> dict:
        return self.call("/state")["state"].get("studio") or {}


def wait_boot(dev: Device, timeout: int = 600) -> None:
    end = time.time() + timeout
    while time.time() < end:
        if dev.adb("shell", "getprop", "sys.boot_completed", check=False).strip() == "1":
            return
        time.sleep(3)
    raise RuntimeError("emulator did not finish booting")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--serial", default="emulator-5560")
    ap.add_argument("--avd", default="doneirl_tv30", help="AVD to boot when --boot is given")
    ap.add_argument("--boot", action="store_true", help="boot the AVD (port taken from --serial)")
    ap.add_argument(
        "--apk", default=str(ROOT / "apps/firetv-command-hud/app/build/outputs/apk/debug/app-debug.apk")
    )
    ap.add_argument(
        "--backend", default="http://127.0.0.1:8080", help="host backend (reversed into the emulator)"
    )
    ap.add_argument("--out", default=str(ROOT / "docs/evidence/firetv"))
    ap.add_argument("--record", action="store_true", help="screenrecord the D-pad walkthrough")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    dev = Device(args.serial, out)
    port = int(args.backend.rsplit(":", 1)[1])
    password = json.loads((ROOT / ".local/access.json").read_text())["demo-admin"]

    if args.boot:
        subprocess.Popen(
            [
                EMULATOR,
                "-avd",
                args.avd,
                "-port",
                args.serial.split("-")[1],
                "-no-snapshot",
                "-no-audio",
                "-no-boot-anim",
                "-gpu",
                "swiftshader_indirect",
            ],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        subprocess.run([ADB, "wait-for-device"], timeout=600)
    wait_boot(dev)
    props = {
        k: dev.adb("shell", "getprop", k).strip()
        for k in (
            "ro.build.version.sdk",
            "ro.build.version.release",
            "ro.product.model",
            "ro.build.fingerprint",
            "ro.build.characteristics",
        )
    }
    record("emulator booted", True, json.dumps(props))
    apk_sha = hashlib.sha256(Path(args.apk).read_bytes()).hexdigest()
    record("apk sha256", True, apk_sha)

    # Admin side: reset the synthetic household and play the canonical day (stages 1-6).
    admin = Admin(args.backend)
    admin.login(password)
    admin.call("/admin/reset", {})
    branches = {1: "deposit", 2: "deposit", 3: "disengaged", 4: "unknown", 5: "empty", 6: "deposit"}
    for stage, branch in branches.items():
        admin.call(f"/admin/scenarios/{stage}/run", {"branch": branch})
    state = admin.call("/state")["state"]
    record(
        "backend scenarios 1-6 played",
        True,
        f"{len(state.get('contracts', []))} contracts, {len(state.get('incidents', []))} incidents",
    )

    # Install + fresh launch, connect, sign in with the remote only.
    dev.adb("install", "-r", args.apk, timeout=300)
    record("apk installed", True)
    dev.adb("reverse", f"tcp:{port}", f"tcp:{port}")
    dev.adb("shell", "pm", "clear", PKG)
    launch = dev.adb("shell", "am", "start", "-W", "-n", ACTIVITY)
    record("cold launch", "Status: ok" in launch, re.search(r"TotalTime: \d+", launch).group(0))
    time.sleep(2)
    dev.shot("01-connection-dialog")
    dev.adb("shell", "input", "text", f"http://127.0.0.1:{port}")
    dev.key("ENTER", 4)
    dev.key("DPAD_DOWN")  # web focus -> username (IME opens)
    dev.key("BACK", 0.6)  # IME closes
    dev.key("DPAD_DOWN")  # password (IME opens)
    tools = DevTools(dev)
    # `input text` can drop characters when injected quickly into an IME-attached WebView field,
    # so type in short chunks and compare only the field LENGTH (never the value); retry if short.
    pw_len = "document.activeElement && document.activeElement.type === 'password' ? document.activeElement.value.length : -1"
    for attempt in range(3):
        for i in range(0, len(password), 6):
            dev.adb("shell", "input", "text", password[i : i + 6])
            time.sleep(0.4)
        if tools.evaluate(pw_len) == len(password):
            break
        dev.key("MOVE_END", 0.2)
        for _ in range(len(password) + 5):
            dev.adb("shell", "input", "keyevent", "KEYCODE_DEL")
    record(
        "password entered via remote keyboard (length verified)",
        tools.evaluate(pw_len) == len(password),
        f"attempts={attempt + 1}",
    )
    dev.key("BACK", 0.6)
    dev.key("DPAD_DOWN")  # "Open mission control"
    dev.key("ENTER", 5)
    signed_in = tools.evaluate(
        "!!document.querySelector('.app') && !document.querySelector('input[type=password]')"
    )
    record("signed in via D-pad + remote keyboard", bool(signed_in))
    dev.shot("02-ledger")

    # Record only the D-pad walkthrough and Reality-Lock (sign-in is deliberately not recorded).
    rec = None
    if args.record:
        dev.adb("shell", "rm", "-f", "/sdcard/doneirl-walk.mp4", check=False)
        rec = subprocess.Popen(
            [
                ADB,
                "-s",
                args.serial,
                "shell",
                "screenrecord",
                "--time-limit",
                "170",
                "--size",
                "1280x720",
                "--bit-rate",
                "4000000",
                "/sdcard/doneirl-walk.mp4",
            ]
        )

    # Walk all four views with the remote only.
    for i, name in enumerate(VIEWS):
        dev.key("BACK")  # focus -> native view bar (current view button)
        f = dev.native_focus()
        record(f"Back moves focus to view bar ({name} step)", f in VIEWS, f"native focus='{f}'")
        if i == 0:
            dev.shot("03-viewbar-focus")
        else:
            dev.key("DPAD_RIGHT")
            f = dev.native_focus()
            record(f"DPAD_RIGHT focuses '{name}'", f == name, f"native focus='{f}'")
        dev.key("ENTER", 3.5)
        f = dev.native_focus()
        # Focus inside the WebView is reported as the WebView or its document node (page title).
        record(
            f"ENTER opens {name}; focus enters web content",
            bool(f) and f not in [*VIEWS, "Connection"],
            f"native focus='{f}'",
        )
        seen = []
        for _ in range(3):
            dev.key("DPAD_DOWN", 0.7)
            seen.append(tools.active())
        record(f"{name}: DPAD_DOWN moves visible web focus", len(set(seen)) > 1, " || ".join(seen))
        dev.shot(f"1{i}-{name.lower().replace(' ', '-').replace('-lock', 'lock')}")

    # Reality-Lock 14/15 stays locked; 15/15 unlocks (synthetic marker frames, admin studio).
    admin.call("/studio/sessions", {})
    for _ in range(400):
        st = admin.studio()
        if st.get("count", 0) >= 14:
            break
        admin.call("/admin/studio/frame-step", {})
    st = admin.studio()
    record(
        "Reality-Lock 14/15 stays locked",
        st.get("count") == 14 and st.get("gate") != "UNLOCKED",
        f"count={st.get('count')} gate={st.get('gate')}",
    )
    time.sleep(4)
    counter_js = (
        "(() => { const e = [...document.querySelectorAll('*')].find(n => n.childElementCount === 0"
        " && /verified cycles/i.test(n.textContent)); if (!e) return 'missing';"
        " const r = e.getBoundingClientRect(); return (r.top >= 0 && r.bottom <= innerHeight) ? 'visible' : 'offscreen'; })()"
    )
    presses = 0
    while tools.evaluate(counter_js) != "visible" and presses < 10:
        dev.key("DPAD_DOWN", 0.8)
        presses += 1
    seen_text = tools.evaluate("document.body.innerText") or ""
    record(
        "D-pad reveals Reality-Lock counter (no unreachable content)",
        tools.evaluate(counter_js) == "visible",
        f"{presses} DPAD_DOWN presses",
    )
    record(
        "TV shows 14/15 and gate locked",
        re.search(r"\b14\s*/\s*15", seen_text) is not None
        and not re.search(r"gate unlocked", seen_text, re.I),
        "web text '14 / 15', no 'gate unlocked'",
    )
    dev.shot("20-realitylock-14of15-locked")
    for _ in range(100):
        st = admin.studio()
        if st.get("gate") == "UNLOCKED" or st.get("count", 0) >= 15:
            break
        admin.call("/admin/studio/frame-step", {})
    time.sleep(1)
    st = admin.studio()
    record(
        "Reality-Lock 15/15 unlocks",
        st.get("count") == 15 and st.get("gate") == "UNLOCKED",
        f"count={st.get('count')} gate={st.get('gate')}",
    )
    time.sleep(6)
    while tools.evaluate(counter_js) != "visible" and presses < 20:
        dev.key("DPAD_DOWN", 0.8)
        presses += 1
    dev.shot("21-realitylock-15of15-unlocked")
    if rec:
        time.sleep(1)
        dev.adb("shell", "pkill", "-INT", "screenrecord", check=False)  # graceful stop finalizes the mp4
        try:
            rec.wait(timeout=15)
        except subprocess.TimeoutExpired:
            rec.kill()
        time.sleep(2)
        dev.adb("pull", "/sdcard/doneirl-walk.mp4", str(out / "walkthrough-raw.mp4"), check=False)

    tv_text = tools.evaluate("document.body.innerText") or ""
    record(
        "TV view reflects live 15/15 state",
        re.search(r"\b15\s*/\s*15", tv_text) is not None
        and re.search(r"gate unlocked", tv_text, re.I) is not None,
        "web text '15 / 15' and 'gate unlocked'",
    )

    # Network loss and recovery while the app is in the foreground.
    dev.adb("shell", "cmd", "connectivity", "airplane-mode", "enable")
    time.sleep(5)
    lost = dev.screen_text()
    dev.shot("22-network-lost")
    record("network loss shows honest offline message", "Network lost" in lost, "status bar text checked")
    dev.adb("shell", "cmd", "connectivity", "airplane-mode", "disable")
    time.sleep(10)
    back = dev.screen_text()
    record(
        "network return reloads live view",
        "Network lost" not in back and bool(tools.evaluate("!!document.querySelector('.app')")),
        "offline message cleared, HUD reloaded",
    )

    # Restart: force-stop + relaunch keeps backend URL, session cookie, last view and server state.
    dev.adb("shell", "am", "force-stop", PKG)
    time.sleep(1)
    launch = dev.adb("shell", "am", "start", "-W", "-n", ACTIVITY)
    time.sleep(6)
    f = dev.native_focus()
    still_in = tools.evaluate(
        "!!document.querySelector('.app') && !document.querySelector('input[type=password]')"
    )
    page = tools.evaluate("location.search")
    record(
        "restart keeps connection, session and last view",
        bool(still_in) and "studio" in (page or ""),
        f"signed_in={still_in} url={page} focus='{f}'",
    )
    dev.shot("30-after-restart")

    # Back from a view's bar returns to Ledger; Back on Ledger's bar exits to the TV home.
    dev.key("BACK")
    dev.key("BACK", 3)
    f = dev.native_focus()
    record("Back on view bar returns to Ledger", f == "Ledger", f"native focus='{f}'")
    dev.key("BACK", 2)
    top = dev.top_package()
    record("Back on Ledger bar exits app (no trap)", top != PKG, f"top package='{top}'")
    # (No screenshot of the TV home: it shows third-party content.) Verify launcher registration instead.
    leanback = dev.adb(
        "shell",
        "cmd",
        "package",
        "query-activities",
        "-a",
        "android.intent.action.MAIN",
        "-c",
        "android.intent.category.LEANBACK_LAUNCHER",
        check=False,
    )
    record("app registered as LEANBACK_LAUNCHER entry (TV home row)", PKG in leanback)
    (out / "run-results.json").write_text(
        json.dumps({"apk_sha256": apk_sha, "device": props, "results": results}, indent=2)
    )
    failed = [r for r in results if not r["ok"]]
    print(f"{len(results) - len(failed)}/{len(results)} checks passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
